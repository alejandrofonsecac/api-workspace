-- Baseline for new databases. Existing installations retain their tables and data.
CREATE TABLE IF NOT EXISTS tb_note (
    id varchar(255) PRIMARY KEY, title varchar(255), description text,
    edited timestamp(6), favourite boolean, fixed boolean, fixed_at timestamp(6)
);
CREATE SEQUENCE IF NOT EXISTS tb_tasks_seq START WITH 1 INCREMENT BY 50;
CREATE TABLE IF NOT EXISTS tb_tasks (
    id bigint PRIMARY KEY, title varchar(255), priority varchar(255), due_label varchar(255),
    completed boolean, notes text, task_created_date date, due_date date
);
CREATE TABLE IF NOT EXISTS tb_event (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255), description varchar(255), start_time time(6), end_time time(6), category varchar(255)
);
CREATE TABLE IF NOT EXISTS events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL, date date NOT NULL,
    start_time time(6) NOT NULL, end_time time(6) NOT NULL, description text, location varchar(255),
    source varchar(255) NOT NULL, category varchar(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS tb_habit (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255), category varchar(255), frequency_every_day boolean, local_date date,
    objective varchar(255), observation varchar(255)
);
CREATE TABLE IF NOT EXISTS tb_habit_completions (
    habit_id integer NOT NULL REFERENCES tb_habit(id), completed_date date NOT NULL,
    UNIQUE (habit_id, completed_date)
);
CREATE TABLE IF NOT EXISTS tb_goals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_name varchar(255) NOT NULL, expected_target varchar(255) NOT NULL,
    priority varchar(255) NOT NULL, category varchar(255) NOT NULL,
    week_id varchar(8), created_at timestamp(6) with time zone,
    completed_at timestamp(6) with time zone, deferred_count integer DEFAULT 0 NOT NULL
);
CREATE TABLE IF NOT EXISTS tb_goal_focus (
    week_id varchar(8) PRIMARY KEY, focus varchar(255) NOT NULL, message varchar(2000) NOT NULL
);
